-- Partial returns against saved invoices. Each returned line points at the original document line,
-- and the total returned per line can never exceed what was sold / bought (enforced in the service
-- under a lock on the original document; the per-line quantity check below is a safety net).
--
-- Amount per returned line = original line total x returned qty / original qty (half-up); when the
-- last units of a line are returned, the exact remainder is used so refunds never exceed the charge.

CREATE TABLE sale_return (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_number VARCHAR(20)    NOT NULL,
    sale_id       BIGINT         NOT NULL REFERENCES sale (id),
    return_date   DATE           NOT NULL,
    total         NUMERIC(14, 2) NOT NULL,
    reason        VARCHAR(500)   NOT NULL,
    notes         VARCHAR(500),
    created_at    TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ    NOT NULL DEFAULT now(),
    created_by    BIGINT         NOT NULL REFERENCES app_user (id),
    updated_by    BIGINT REFERENCES app_user (id),
    version       BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uq_sale_return_number UNIQUE (return_number),
    CONSTRAINT chk_sale_return_total CHECK (total >= 0)
);

CREATE INDEX ix_sale_return_sale ON sale_return (sale_id);
CREATE INDEX ix_sale_return_date ON sale_return (return_date DESC, id DESC);

CREATE TABLE sale_return_item (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_return_id BIGINT         NOT NULL REFERENCES sale_return (id) ON DELETE CASCADE,
    sale_item_id   BIGINT         NOT NULL REFERENCES sale_item (id),
    product_id     BIGINT         NOT NULL REFERENCES product (id),
    quantity       INTEGER        NOT NULL,
    line_total     NUMERIC(14, 2) NOT NULL,
    CONSTRAINT uq_sale_return_item UNIQUE (sale_return_id, sale_item_id),
    CONSTRAINT chk_sale_return_item_quantity CHECK (quantity > 0),
    CONSTRAINT chk_sale_return_item_total CHECK (line_total >= 0)
);

CREATE INDEX ix_sale_return_item_sale_item ON sale_return_item (sale_item_id);
CREATE INDEX ix_sale_return_item_product ON sale_return_item (product_id);

CREATE TABLE purchase_return (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_number VARCHAR(20)    NOT NULL,
    purchase_id   BIGINT         NOT NULL REFERENCES purchase (id),
    return_date   DATE           NOT NULL,
    total         NUMERIC(14, 2) NOT NULL,
    reason        VARCHAR(500)   NOT NULL,
    notes         VARCHAR(500),
    created_at    TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ    NOT NULL DEFAULT now(),
    created_by    BIGINT         NOT NULL REFERENCES app_user (id),
    updated_by    BIGINT REFERENCES app_user (id),
    version       BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uq_purchase_return_number UNIQUE (return_number),
    CONSTRAINT chk_purchase_return_total CHECK (total >= 0)
);

CREATE INDEX ix_purchase_return_purchase ON purchase_return (purchase_id);
CREATE INDEX ix_purchase_return_date ON purchase_return (return_date DESC, id DESC);

CREATE TABLE purchase_return_item (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_return_id BIGINT         NOT NULL REFERENCES purchase_return (id) ON DELETE CASCADE,
    purchase_item_id   BIGINT         NOT NULL REFERENCES purchase_item (id),
    product_id         BIGINT         NOT NULL REFERENCES product (id),
    quantity           INTEGER        NOT NULL,
    line_total         NUMERIC(14, 2) NOT NULL,
    CONSTRAINT uq_purchase_return_item UNIQUE (purchase_return_id, purchase_item_id),
    CONSTRAINT chk_purchase_return_item_quantity CHECK (quantity > 0),
    CONSTRAINT chk_purchase_return_item_total CHECK (line_total >= 0)
);

CREATE INDEX ix_purchase_return_item_purchase_item ON purchase_return_item (purchase_item_id);
CREATE INDEX ix_purchase_return_item_product ON purchase_return_item (product_id);
