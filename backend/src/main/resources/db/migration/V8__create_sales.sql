-- Sales invoices. Same money rules as purchases (see V7):
--   subtotal       = SUM(line gross)
--   discount_total = SUM(line discount amounts) + invoice_discount
--   tax_total      = SUM(line tax amounts)
--   total          = subtotal - discount_total + tax_total
CREATE TABLE sale (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number   VARCHAR(20)    NOT NULL,
    customer_id      BIGINT         NOT NULL REFERENCES customer (id),
    sale_date        DATE           NOT NULL,
    subtotal         NUMERIC(14, 2) NOT NULL,
    invoice_discount NUMERIC(14, 2) NOT NULL DEFAULT 0,
    discount_total   NUMERIC(14, 2) NOT NULL,
    tax_total        NUMERIC(14, 2) NOT NULL,
    total            NUMERIC(14, 2) NOT NULL,
    payment_status   VARCHAR(10)    NOT NULL,
    status           VARCHAR(10)    NOT NULL DEFAULT 'COMPLETED',
    notes            VARCHAR(500),
    cancelled_at     TIMESTAMPTZ,
    cancelled_by     BIGINT REFERENCES app_user (id),
    cancel_reason    VARCHAR(500),
    created_at       TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ    NOT NULL DEFAULT now(),
    created_by       BIGINT         NOT NULL REFERENCES app_user (id),
    updated_by       BIGINT REFERENCES app_user (id),
    version          BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uq_sale_invoice_number UNIQUE (invoice_number),
    CONSTRAINT chk_sale_payment_status CHECK (payment_status IN ('PAID', 'UNPAID', 'PARTIAL')),
    CONSTRAINT chk_sale_status CHECK (status IN ('COMPLETED', 'CANCELLED')),
    CONSTRAINT chk_sale_amounts CHECK (subtotal >= 0 AND invoice_discount >= 0 AND discount_total >= 0
                                       AND tax_total >= 0 AND total >= 0),
    CONSTRAINT chk_sale_total CHECK (total = subtotal - discount_total + tax_total),
    CONSTRAINT chk_sale_cancel CHECK ((status = 'CANCELLED') = (cancelled_at IS NOT NULL))
);

CREATE INDEX ix_sale_date ON sale (sale_date DESC, id DESC);
CREATE INDEX ix_sale_customer ON sale (customer_id, sale_date DESC);
CREATE INDEX ix_sale_status ON sale (status, payment_status);
CREATE INDEX ix_sale_created_by ON sale (created_by, sale_date DESC);

CREATE TABLE sale_item (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id          BIGINT         NOT NULL REFERENCES sale (id) ON DELETE CASCADE,
    line_no          INTEGER        NOT NULL,
    product_id       BIGINT         NOT NULL REFERENCES product (id),
    quantity         INTEGER        NOT NULL,
    unit_price       NUMERIC(12, 2) NOT NULL,
    discount_percent NUMERIC(5, 2)  NOT NULL DEFAULT 0,
    discount_amount  NUMERIC(14, 2) NOT NULL DEFAULT 0,
    tax_percent      NUMERIC(5, 2)  NOT NULL DEFAULT 0,
    tax_amount       NUMERIC(14, 2) NOT NULL DEFAULT 0,
    line_total       NUMERIC(14, 2) NOT NULL,
    CONSTRAINT uq_sale_item_line UNIQUE (sale_id, line_no),
    CONSTRAINT uq_sale_item_product UNIQUE (sale_id, product_id),
    CONSTRAINT chk_sale_item_quantity CHECK (quantity > 0),
    CONSTRAINT chk_sale_item_price CHECK (unit_price > 0),
    CONSTRAINT chk_sale_item_percents CHECK (discount_percent BETWEEN 0 AND 100 AND tax_percent BETWEEN 0 AND 100),
    CONSTRAINT chk_sale_item_total CHECK (line_total = quantity * unit_price - discount_amount + tax_amount)
);

CREATE INDEX ix_sale_item_product ON sale_item (product_id);
