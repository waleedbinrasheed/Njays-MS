-- Representatives: the shop sells to representatives, who supply their own customers.
-- A sale's buyer is now its representative; the customer on a sale is optional ("for which of the
-- representative's customers"). Sales made before this change keep their customer and have no
-- representative ("Unassigned" in history and reports).

CREATE TABLE representative (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(150) NOT NULL,
    phone      VARCHAR(30),
    email      VARCHAR(150),
    address    VARCHAR(500),
    area       VARCHAR(150),
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    -- The single built-in "Counter Sales" representative used for sales over the shop counter.
    built_in   BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by BIGINT REFERENCES app_user (id),
    updated_by BIGINT REFERENCES app_user (id),
    version    BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT chk_representative_name CHECK (btrim(name) <> ''),
    CONSTRAINT chk_representative_built_in_active CHECK (NOT built_in OR active)
);

CREATE UNIQUE INDEX uq_representative_name ON representative (lower(name));
CREATE UNIQUE INDEX uq_representative_built_in ON representative (built_in) WHERE built_in;
CREATE INDEX ix_representative_area ON representative (lower(area));

INSERT INTO representative (name, area, built_in) VALUES ('Counter Sales', 'Shop counter', TRUE);

-- Each customer belongs to one representative (required by the application on create/edit,
-- except the walk-in customer; existing customers start unassigned).
ALTER TABLE customer ADD COLUMN representative_id BIGINT REFERENCES representative (id);
CREATE INDEX ix_customer_representative ON customer (representative_id);

ALTER TABLE sale ADD COLUMN representative_id BIGINT REFERENCES representative (id);
ALTER TABLE sale ALTER COLUMN customer_id DROP NOT NULL;
-- Every sale has a buyer: a representative (new sales) or a customer (sales from before this change).
ALTER TABLE sale ADD CONSTRAINT chk_sale_party CHECK (representative_id IS NOT NULL OR customer_id IS NOT NULL);
CREATE INDEX ix_sale_representative ON sale (representative_id, sale_date DESC);
