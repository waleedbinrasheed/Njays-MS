-- Current stock: exactly one row per product (single company-wide stock location, no branches).
-- quantity is only ever changed by InventoryService, which writes a stock_transaction each time.

CREATE TABLE inventory (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Cascade only removes the stock row of a product that was never used; once a product has
    -- stock history, the stock_transaction foreign key blocks deleting it.
    product_id    BIGINT      NOT NULL REFERENCES product (id) ON DELETE CASCADE,
    quantity      INTEGER     NOT NULL DEFAULT 0,
    reorder_level INTEGER     NOT NULL DEFAULT 0,
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    version       BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uq_inventory_product UNIQUE (product_id),
    CONSTRAINT chk_inventory_quantity CHECK (quantity >= 0),
    CONSTRAINT chk_inventory_reorder_level CHECK (reorder_level >= 0)
);

-- Low-stock queries compare quantity with reorder_level.
CREATE INDEX ix_inventory_low_stock ON inventory (quantity, reorder_level);

-- Products created before this migration start with zero stock.
INSERT INTO inventory (product_id) SELECT id FROM product;
