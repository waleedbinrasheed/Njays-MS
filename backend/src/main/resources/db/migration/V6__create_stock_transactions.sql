-- Immutable ledger of every stock change. For any product:
--   inventory.quantity = SUM(stock_transaction.quantity)
-- and each row's resulting_quantity = previous_quantity + quantity.

CREATE TABLE stock_transaction (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id         BIGINT       NOT NULL REFERENCES product (id),
    transaction_type   VARCHAR(20)  NOT NULL,
    quantity           INTEGER      NOT NULL,
    reference_type     VARCHAR(20),
    reference_id       BIGINT,
    previous_quantity  INTEGER      NOT NULL,
    resulting_quantity INTEGER      NOT NULL,
    created_by         BIGINT       NOT NULL REFERENCES app_user (id),
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    notes              VARCHAR(500),
    CONSTRAINT chk_stock_tx_type CHECK (transaction_type IN
        ('PURCHASE', 'SALE', 'SALE_RETURN', 'PURCHASE_RETURN', 'ADJUSTMENT', 'PURCHASE_CANCEL', 'SALE_CANCEL')),
    CONSTRAINT chk_stock_tx_reference_type CHECK (reference_type IS NULL OR reference_type IN
        ('PURCHASE', 'SALE', 'SALE_RETURN', 'PURCHASE_RETURN', 'ADJUSTMENT')),
    CONSTRAINT chk_stock_tx_quantity CHECK (quantity <> 0),
    CONSTRAINT chk_stock_tx_non_negative CHECK (previous_quantity >= 0 AND resulting_quantity >= 0),
    CONSTRAINT chk_stock_tx_arithmetic CHECK (resulting_quantity = previous_quantity + quantity)
);

CREATE INDEX ix_stock_tx_product_created ON stock_transaction (product_id, created_at DESC, id DESC);
CREATE INDEX ix_stock_tx_created ON stock_transaction (created_at DESC, id DESC);
CREATE INDEX ix_stock_tx_type_created ON stock_transaction (transaction_type, created_at DESC);
CREATE INDEX ix_stock_tx_reference ON stock_transaction (reference_type, reference_id);

-- Manual corrections (damage, loss, physical count...). Each one writes one stock_transaction
-- of type ADJUSTMENT with reference_type = 'ADJUSTMENT' and reference_id = stock_adjustment.id.
CREATE TABLE stock_adjustment (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id          BIGINT       NOT NULL REFERENCES product (id),
    reason              VARCHAR(30)  NOT NULL,
    previous_quantity   INTEGER      NOT NULL,
    adjustment_quantity INTEGER      NOT NULL,
    resulting_quantity  INTEGER      NOT NULL,
    notes               VARCHAR(500),
    created_by          BIGINT       NOT NULL REFERENCES app_user (id),
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT chk_adjustment_reason CHECK (reason IN ('DAMAGED', 'LOST', 'COUNT_CORRECTION', 'FOUND', 'OTHER')),
    CONSTRAINT chk_adjustment_quantity CHECK (adjustment_quantity <> 0),
    CONSTRAINT chk_adjustment_arithmetic CHECK (resulting_quantity = previous_quantity + adjustment_quantity),
    CONSTRAINT chk_adjustment_non_negative CHECK (previous_quantity >= 0 AND resulting_quantity >= 0)
);

CREATE INDEX ix_stock_adjustment_product ON stock_adjustment (product_id, created_at DESC);
CREATE INDEX ix_stock_adjustment_created ON stock_adjustment (created_at DESC);
