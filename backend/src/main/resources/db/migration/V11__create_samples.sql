-- Samples: books handed to a representative to show their customers. Recorded as "SAMPLE SALE"
-- documents at (roughly) cost, kept completely separate from sales: they never count in sales totals.
-- Issuing takes stock out; sample returns (partial allowed) put it back at the ORIGINAL sample price.
-- The outstanding quantity/amount (issued - returned) is tracked and reported only; nothing is paid.

CREATE TABLE sample_issue (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sample_number     VARCHAR(20)    NOT NULL,
    representative_id BIGINT         NOT NULL REFERENCES representative (id),
    issue_date        DATE           NOT NULL,
    total_quantity    INTEGER        NOT NULL,
    total             NUMERIC(14, 2) NOT NULL,
    -- Running totals of all returns against this sample (updated under a lock on this row).
    returned_quantity INTEGER        NOT NULL DEFAULT 0,
    returned_total    NUMERIC(14, 2) NOT NULL DEFAULT 0,
    -- ISSUED -> PARTIALLY_RETURNED -> RETURNED, or CANCELLED (only while nothing is returned).
    status            VARCHAR(20)    NOT NULL DEFAULT 'ISSUED',
    notes             VARCHAR(500),
    cancelled_at      TIMESTAMPTZ,
    cancelled_by      BIGINT REFERENCES app_user (id),
    cancel_reason     VARCHAR(500),
    created_at        TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ    NOT NULL DEFAULT now(),
    created_by        BIGINT         NOT NULL REFERENCES app_user (id),
    updated_by        BIGINT REFERENCES app_user (id),
    version           BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uq_sample_issue_number UNIQUE (sample_number),
    CONSTRAINT chk_sample_issue_status CHECK (status IN ('ISSUED', 'PARTIALLY_RETURNED', 'RETURNED', 'CANCELLED')),
    CONSTRAINT chk_sample_issue_amounts CHECK (total_quantity > 0 AND total >= 0
                                               AND returned_quantity BETWEEN 0 AND total_quantity
                                               AND returned_total BETWEEN 0 AND total),
    CONSTRAINT chk_sample_issue_cancel CHECK ((status = 'CANCELLED') = (cancelled_at IS NOT NULL)),
    CONSTRAINT chk_sample_issue_cancel_unreturned CHECK (status <> 'CANCELLED' OR returned_quantity = 0)
);

CREATE INDEX ix_sample_issue_date ON sample_issue (issue_date DESC, id DESC);
CREATE INDEX ix_sample_issue_representative ON sample_issue (representative_id, issue_date DESC);
CREATE INDEX ix_sample_issue_status ON sample_issue (status);

CREATE TABLE sample_issue_item (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sample_issue_id  BIGINT         NOT NULL REFERENCES sample_issue (id) ON DELETE CASCADE,
    line_no          INTEGER        NOT NULL,
    product_id       BIGINT         NOT NULL REFERENCES product (id),
    quantity         INTEGER        NOT NULL,
    -- Snapshot of the sample price (defaults to the book's purchase price, never above its selling price).
    unit_price       NUMERIC(12, 2) NOT NULL,
    line_total       NUMERIC(14, 2) NOT NULL,
    CONSTRAINT uq_sample_issue_item_line UNIQUE (sample_issue_id, line_no),
    CONSTRAINT uq_sample_issue_item_product UNIQUE (sample_issue_id, product_id),
    CONSTRAINT chk_sample_issue_item_quantity CHECK (quantity > 0),
    CONSTRAINT chk_sample_issue_item_price CHECK (unit_price >= 0),
    CONSTRAINT chk_sample_issue_item_total CHECK (line_total = quantity * unit_price)
);

CREATE INDEX ix_sample_issue_item_product ON sample_issue_item (product_id);

CREATE TABLE sample_return (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_number   VARCHAR(20)    NOT NULL,
    sample_issue_id BIGINT         NOT NULL REFERENCES sample_issue (id),
    return_date     DATE           NOT NULL,
    total_quantity  INTEGER        NOT NULL,
    total           NUMERIC(14, 2) NOT NULL,
    notes           VARCHAR(500),
    created_at      TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ    NOT NULL DEFAULT now(),
    created_by      BIGINT         NOT NULL REFERENCES app_user (id),
    updated_by      BIGINT REFERENCES app_user (id),
    version         BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uq_sample_return_number UNIQUE (return_number),
    CONSTRAINT chk_sample_return_amounts CHECK (total_quantity > 0 AND total >= 0)
);

CREATE INDEX ix_sample_return_issue ON sample_return (sample_issue_id);
CREATE INDEX ix_sample_return_date ON sample_return (return_date DESC, id DESC);

CREATE TABLE sample_return_item (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sample_return_id     BIGINT         NOT NULL REFERENCES sample_return (id) ON DELETE CASCADE,
    sample_issue_item_id BIGINT         NOT NULL REFERENCES sample_issue_item (id),
    product_id           BIGINT         NOT NULL REFERENCES product (id),
    quantity             INTEGER        NOT NULL,
    -- quantity x the ORIGINAL sample price of the issued line.
    unit_price           NUMERIC(12, 2) NOT NULL,
    line_total           NUMERIC(14, 2) NOT NULL,
    CONSTRAINT uq_sample_return_item UNIQUE (sample_return_id, sample_issue_item_id),
    CONSTRAINT chk_sample_return_item_quantity CHECK (quantity > 0),
    CONSTRAINT chk_sample_return_item_total CHECK (line_total = quantity * unit_price)
);

CREATE INDEX ix_sample_return_item_issue_item ON sample_return_item (sample_issue_item_id);
CREATE INDEX ix_sample_return_item_product ON sample_return_item (product_id);

-- Stock ledger: new movement and reference kinds.
ALTER TABLE stock_transaction DROP CONSTRAINT chk_stock_tx_type;
ALTER TABLE stock_transaction ADD CONSTRAINT chk_stock_tx_type CHECK (transaction_type IN
    ('PURCHASE', 'SALE', 'SALE_RETURN', 'PURCHASE_RETURN', 'ADJUSTMENT', 'PURCHASE_CANCEL', 'SALE_CANCEL',
     'SAMPLE_ISSUE', 'SAMPLE_RETURN', 'SAMPLE_CANCEL'));
ALTER TABLE stock_transaction DROP CONSTRAINT chk_stock_tx_reference_type;
ALTER TABLE stock_transaction ADD CONSTRAINT chk_stock_tx_reference_type CHECK (reference_type IS NULL OR reference_type IN
    ('PURCHASE', 'SALE', 'SALE_RETURN', 'PURCHASE_RETURN', 'ADJUSTMENT', 'SAMPLE_ISSUE', 'SAMPLE_RETURN'));

-- Permissions: everyone with the standard roles can look; only ADMIN can issue, return and cancel.
INSERT INTO permission (code, module, description) VALUES
    ('SAMPLE_VIEW',   'Samples', 'View sample issues, sample returns, representative sample history and the sample report'),
    ('SAMPLE_MANAGE', 'Samples', 'Issue samples to representatives, record sample returns and cancel samples');

