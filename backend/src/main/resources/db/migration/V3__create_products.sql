-- Product master. Books are the only type today; book-specific columns are nullable so other
-- product types can be added later by widening chk_product_type, without a redesign.
-- Reorder level is deliberately NOT here: it lives on the inventory table.

CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE product (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_type     VARCHAR(20)   NOT NULL DEFAULT 'BOOK',
    isbn             VARCHAR(13),
    title            VARCHAR(300)  NOT NULL,
    author           VARCHAR(200),
    publisher_id     BIGINT REFERENCES publisher (id),
    category_id      BIGINT REFERENCES category (id),
    edition          VARCHAR(50),
    publication_year SMALLINT,
    purchase_price   NUMERIC(12, 2) NOT NULL,
    selling_price    NUMERIC(12, 2) NOT NULL,
    active           BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by       BIGINT REFERENCES app_user (id),
    updated_by       BIGINT REFERENCES app_user (id),
    version          BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT chk_product_type CHECK (product_type IN ('BOOK')),
    CONSTRAINT chk_product_title CHECK (btrim(title) <> ''),
    -- Stored normalised: 10 or 13 characters, digits only (ISBN-10 may end in X).
    CONSTRAINT chk_product_isbn CHECK (isbn IS NULL OR isbn ~ '^([0-9]{9}[0-9X]|[0-9]{13})$'),
    CONSTRAINT chk_product_year CHECK (publication_year IS NULL OR publication_year BETWEEN 1450 AND 2100),
    CONSTRAINT chk_product_purchase_price CHECK (purchase_price >= 0),
    CONSTRAINT chk_product_selling_price CHECK (selling_price > 0)
);

CREATE UNIQUE INDEX uq_product_isbn ON product (isbn) WHERE isbn IS NOT NULL;
CREATE INDEX ix_product_publisher ON product (publisher_id);
CREATE INDEX ix_product_category ON product (category_id);
-- Fast "contains" search on title / author (used by product search in sales and purchases).
CREATE INDEX ix_product_title_trgm ON product USING gin (lower(title) gin_trgm_ops);
CREATE INDEX ix_product_author_trgm ON product USING gin (lower(author) gin_trgm_ops);
