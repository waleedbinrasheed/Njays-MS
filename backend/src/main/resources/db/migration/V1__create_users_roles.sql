-- Users, roles and permissions.
-- Code authorizes on permission codes, never on role names, so new roles are pure data.
-- The first admin account is created at startup by AdminBootstrap (no password in migrations).

CREATE TABLE app_user (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username             VARCHAR(50)  NOT NULL,
    password_hash        VARCHAR(100) NOT NULL,
    full_name            VARCHAR(100) NOT NULL,
    email                VARCHAR(150),
    mobile               VARCHAR(30),
    active               BOOLEAN      NOT NULL DEFAULT TRUE,
    must_change_password BOOLEAN      NOT NULL DEFAULT FALSE,
    last_login_at        TIMESTAMPTZ,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by           BIGINT REFERENCES app_user (id),
    updated_by           BIGINT REFERENCES app_user (id),
    version              BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT chk_app_user_username CHECK (username ~ '^[A-Za-z0-9._-]{3,50}$')
);

CREATE UNIQUE INDEX uq_app_user_username ON app_user (lower(username));
CREATE UNIQUE INDEX uq_app_user_email ON app_user (lower(email)) WHERE email IS NOT NULL;

CREATE TABLE role (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50)  NOT NULL,
    description VARCHAR(255),
    system_role BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by  BIGINT REFERENCES app_user (id),
    updated_by  BIGINT REFERENCES app_user (id),
    version     BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT chk_role_name CHECK (name ~ '^[A-Z][A-Z0-9_]{1,49}$')
);

CREATE UNIQUE INDEX uq_role_name ON role (name);

CREATE TABLE permission (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(60)  NOT NULL UNIQUE,
    module      VARCHAR(50)  NOT NULL,
    description VARCHAR(255) NOT NULL
);

CREATE TABLE role_permission (
    role_id       BIGINT NOT NULL REFERENCES role (id) ON DELETE CASCADE,
    permission_id BIGINT NOT NULL REFERENCES permission (id),
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE user_role (
    user_id BIGINT NOT NULL REFERENCES app_user (id),
    role_id BIGINT NOT NULL REFERENCES role (id),
    PRIMARY KEY (user_id, role_id)
);

CREATE INDEX ix_user_role_role ON user_role (role_id);

