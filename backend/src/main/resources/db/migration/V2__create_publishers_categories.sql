CREATE TABLE publisher (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(150) NOT NULL,
    contact_person VARCHAR(100),
    phone          VARCHAR(30),
    email          VARCHAR(150),
    address        VARCHAR(500),
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by     BIGINT REFERENCES app_user (id),
    updated_by     BIGINT REFERENCES app_user (id),
    version        BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT chk_publisher_name CHECK (btrim(name) <> '')
);

CREATE UNIQUE INDEX uq_publisher_name ON publisher (lower(name));

CREATE TABLE category (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by  BIGINT REFERENCES app_user (id),
    updated_by  BIGINT REFERENCES app_user (id),
    version     BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT chk_category_name CHECK (btrim(name) <> '')
);

CREATE UNIQUE INDEX uq_category_name ON category (lower(name));
