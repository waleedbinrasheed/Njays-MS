-- Gap-free document numbers per type and year (PUR-2026-000001, INV-2026-000001, ...).
-- The counter row is updated inside the document's own transaction, so a failed save
-- rolls the number back and concurrent saves queue on the row lock.
CREATE TABLE document_sequence (
    doc_type   VARCHAR(20) NOT NULL,
    year       INTEGER     NOT NULL,
    last_value INTEGER     NOT NULL,
    PRIMARY KEY (doc_type, year),
    CONSTRAINT chk_document_sequence_value CHECK (last_value > 0)
);

-- Money is NUMERIC(14,2) PKR. Per line: gross = qty x unit cost; discount and tax are percentages
-- of the line; header invoice_discount is an optional fixed amount off the whole document.
--   subtotal       = SUM(line gross)
--   discount_total = SUM(line discount amounts) + invoice_discount
--   tax_total      = SUM(line tax amounts)
--   total          = subtotal - discount_total + tax_total
CREATE TABLE purchase (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_number         VARCHAR(20)    NOT NULL,
    supplier_id             BIGINT         NOT NULL REFERENCES supplier (id),
    supplier_invoice_number VARCHAR(50),
    purchase_date           DATE           NOT NULL,
    subtotal                NUMERIC(14, 2) NOT NULL,
    invoice_discount        NUMERIC(14, 2) NOT NULL DEFAULT 0,
    discount_total          NUMERIC(14, 2) NOT NULL,
    tax_total               NUMERIC(14, 2) NOT NULL,
    total                   NUMERIC(14, 2) NOT NULL,
    payment_status          VARCHAR(10)    NOT NULL,
    status                  VARCHAR(10)    NOT NULL DEFAULT 'COMPLETED',
    notes                   VARCHAR(500),
    cancelled_at            TIMESTAMPTZ,
    cancelled_by            BIGINT REFERENCES app_user (id),
    cancel_reason           VARCHAR(500),
    created_at              TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ    NOT NULL DEFAULT now(),
    created_by              BIGINT         NOT NULL REFERENCES app_user (id),
    updated_by              BIGINT REFERENCES app_user (id),
    version                 BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uq_purchase_number UNIQUE (purchase_number),
    CONSTRAINT chk_purchase_payment_status CHECK (payment_status IN ('PAID', 'UNPAID', 'PARTIAL')),
    CONSTRAINT chk_purchase_status CHECK (status IN ('COMPLETED', 'CANCELLED')),
    CONSTRAINT chk_purchase_amounts CHECK (subtotal >= 0 AND invoice_discount >= 0 AND discount_total >= 0
                                           AND tax_total >= 0 AND total >= 0),
    CONSTRAINT chk_purchase_total CHECK (total = subtotal - discount_total + tax_total),
    CONSTRAINT chk_purchase_cancel CHECK ((status = 'CANCELLED') = (cancelled_at IS NOT NULL))
);

CREATE INDEX ix_purchase_date ON purchase (purchase_date DESC, id DESC);
CREATE INDEX ix_purchase_supplier ON purchase (supplier_id, purchase_date DESC);
CREATE INDEX ix_purchase_status ON purchase (status, payment_status);

CREATE TABLE purchase_item (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_id      BIGINT         NOT NULL REFERENCES purchase (id) ON DELETE CASCADE,
    line_no          INTEGER        NOT NULL,
    product_id       BIGINT         NOT NULL REFERENCES product (id),
    quantity         INTEGER        NOT NULL,
    unit_cost        NUMERIC(12, 2) NOT NULL,
    discount_percent NUMERIC(5, 2)  NOT NULL DEFAULT 0,
    discount_amount  NUMERIC(14, 2) NOT NULL DEFAULT 0,
    tax_percent      NUMERIC(5, 2)  NOT NULL DEFAULT 0,
    tax_amount       NUMERIC(14, 2) NOT NULL DEFAULT 0,
    line_total       NUMERIC(14, 2) NOT NULL,
    CONSTRAINT uq_purchase_item_line UNIQUE (purchase_id, line_no),
    -- One line per product per purchase (keeps returns and reports unambiguous).
    CONSTRAINT uq_purchase_item_product UNIQUE (purchase_id, product_id),
    CONSTRAINT chk_purchase_item_quantity CHECK (quantity > 0),
    CONSTRAINT chk_purchase_item_cost CHECK (unit_cost >= 0),
    CONSTRAINT chk_purchase_item_percents CHECK (discount_percent BETWEEN 0 AND 100 AND tax_percent BETWEEN 0 AND 100),
    CONSTRAINT chk_purchase_item_total CHECK (line_total = quantity * unit_cost - discount_amount + tax_amount)
);

CREATE INDEX ix_purchase_item_product ON purchase_item (product_id);
