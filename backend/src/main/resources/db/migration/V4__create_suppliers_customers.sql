CREATE TABLE supplier (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(150) NOT NULL,
    contact_person VARCHAR(100),
    phone          VARCHAR(30),
    email          VARCHAR(150),
    address        VARCHAR(500),
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by     BIGINT REFERENCES app_user (id),
    updated_by     BIGINT REFERENCES app_user (id),
    version        BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT chk_supplier_name CHECK (btrim(name) <> '')
);

CREATE UNIQUE INDEX uq_supplier_name ON supplier (lower(name));

-- Customer names are not unique (different people share names).
CREATE TABLE customer (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(150) NOT NULL,
    phone      VARCHAR(30),
    email      VARCHAR(150),
    address    VARCHAR(500),
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    walk_in    BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by BIGINT REFERENCES app_user (id),
    updated_by BIGINT REFERENCES app_user (id),
    version    BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT chk_customer_name CHECK (btrim(name) <> ''),
    CONSTRAINT chk_customer_walk_in_active CHECK (NOT walk_in OR active)
);

CREATE INDEX ix_customer_name ON customer (lower(name));
CREATE INDEX ix_customer_phone ON customer (phone);
-- Exactly one walk-in customer: the default for counter sales.
CREATE UNIQUE INDEX uq_customer_walk_in ON customer (walk_in) WHERE walk_in;

